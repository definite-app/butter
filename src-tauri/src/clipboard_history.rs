use crate::database::{AgentDatabase, ClipboardEntry, NewClipboardEntry};
use std::collections::hash_map::DefaultHasher;
use std::hash::{Hash, Hasher};
use std::path::PathBuf;
use std::sync::Arc;
use std::time::{Duration, SystemTime, UNIX_EPOCH};
use tauri::{AppHandle, Emitter};

pub const MAX_TEXT_ENTRIES: i64 = 200;
pub const MAX_IMAGE_ENTRIES: i64 = 30;
pub const POLL_INTERVAL_MS: u64 = 250;
pub const MAX_TEXT_BYTES: usize = 1_000_000;

fn now_secs() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0)
}

pub fn images_dir() -> Result<PathBuf, String> {
    Ok(crate::paths::butter_config_dir()?.join("clipboard-history"))
}

/// Delete an image file referenced by a clipboard row. In the dev flavor the
/// rows may come from the seeded release DB, so never delete outside dev dirs.
fn remove_image_file(path: &str) {
    if crate::paths::may_delete(std::path::Path::new(path)) {
        let _ = std::fs::remove_file(path);
    }
}

fn hash_bytes(bytes: &[u8]) -> String {
    let mut h = DefaultHasher::new();
    bytes.hash(&mut h);
    format!("{:016x}-{}", h.finish(), bytes.len())
}

fn hash_text(text: &str) -> String {
    hash_bytes(text.as_bytes())
}

fn extension_for_mime(mime: &str) -> &'static str {
    match mime {
        "image/png" => "png",
        "image/tiff" => "tiff",
        "image/jpeg" => "jpg",
        "image/gif" => "gif",
        _ => "img",
    }
}

fn save_image_bytes(bytes: &[u8], mime: &str) -> Result<String, String> {
    let dir = images_dir()?;
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    let filename = format!(
        "clip-{}.{}",
        chrono::Utc::now().format("%Y%m%d-%H%M%S%.3f"),
        extension_for_mime(mime)
    );
    let path = dir.join(filename);
    std::fs::write(&path, bytes).map_err(|e| e.to_string())?;
    Ok(path.to_string_lossy().to_string())
}

fn emit_changed(app: &AppHandle, db: &AgentDatabase) {
    if let Ok(entries) = db.clipboard_list(MAX_TEXT_ENTRIES + MAX_IMAGE_ENTRIES) {
        let _ = app.emit("clipboard-history-changed", entries);
    }
}

#[cfg(target_os = "macos")]
mod mac {
    use objc2::msg_send;
    use objc2::rc::{autoreleasepool, Retained};
    use objc2::ClassType;
    use objc2_app_kit::{
        NSPasteboard, NSPasteboardTypePNG, NSPasteboardTypeString, NSPasteboardTypeTIFF,
        NSWorkspace,
    };
    use objc2_foundation::NSString;

    pub struct PasteboardSnapshot {
        pub change_count: i64,
        pub text: Option<String>,
        pub image: Option<(String, Vec<u8>)>, // (mime, bytes)
        pub source_app: Option<String>,
        pub concealed: bool,
    }

    fn ns_string(s: &str) -> Retained<NSString> {
        NSString::from_str(s)
    }

    fn pb_has_type(pb: &NSPasteboard, type_name: &str) -> bool {
        unsafe {
            let target = ns_string(type_name);
            if let Some(types) = pb.types() {
                for t in types.iter() {
                    let s: &NSString = &t;
                    if s.isEqualToString(&target) {
                        return true;
                    }
                }
            }
            false
        }
    }

    fn pb_string_for_type(pb: &NSPasteboard, type_name: &str) -> Option<String> {
        unsafe {
            let target = ns_string(type_name);
            pb.stringForType(&target).map(|s| s.to_string())
        }
    }

    fn frontmost_app_name() -> Option<String> {
        unsafe {
            let workspace: Retained<NSWorkspace> = msg_send![NSWorkspace::class(), sharedWorkspace];
            let app = workspace.frontmostApplication()?;
            app.localizedName().map(|s| s.to_string())
        }
    }

    /// Cheap read of the pasteboard's change counter. Like all `NSPasteboard`
    /// access this must run on the main thread.
    pub fn change_count() -> i64 {
        autoreleasepool(|_| unsafe {
            let pb_opt: Option<Retained<NSPasteboard>> =
                msg_send![NSPasteboard::class(), generalPasteboard];
            match pb_opt {
                Some(pb) => msg_send![&*pb, changeCount],
                None => i64::MIN,
            }
        })
    }

    pub fn snapshot() -> Option<PasteboardSnapshot> {
        autoreleasepool(|_| unsafe {
            let pb_opt: Option<Retained<NSPasteboard>> =
                msg_send![NSPasteboard::class(), generalPasteboard];
            let pb = pb_opt?;
            let change_count: i64 = msg_send![&*pb, changeCount];

            let concealed = pb_has_type(&pb, "org.nspasteboard.ConcealedType")
                || pb_has_type(&pb, "org.nspasteboard.TransientType")
                || pb_has_type(&pb, "org.nspasteboard.AutoGeneratedType");

            let source_app =
                pb_string_for_type(&pb, "org.nspasteboard.source").or_else(frontmost_app_name);

            let text = pb
                .stringForType(NSPasteboardTypeString)
                .map(|s| s.to_string());

            let image = if let Some(data) = pb.dataForType(NSPasteboardTypePNG) {
                let bytes = data.as_bytes_unchecked().to_vec();
                Some(("image/png".to_string(), bytes))
            } else if let Some(data) = pb.dataForType(NSPasteboardTypeTIFF) {
                let bytes = data.as_bytes_unchecked().to_vec();
                Some(("image/tiff".to_string(), bytes))
            } else {
                None
            };

            Some(PasteboardSnapshot {
                change_count,
                text,
                image,
                source_app,
                concealed,
            })
        })
    }

    pub fn write_text(text: &str) -> Result<(), String> {
        autoreleasepool(|_| unsafe {
            let pb_opt: Option<Retained<NSPasteboard>> =
                msg_send![NSPasteboard::class(), generalPasteboard];
            let pb = pb_opt.ok_or("Failed to access NSPasteboard")?;
            let _: i64 = msg_send![&*pb, clearContents];
            let ns = ns_string(text);
            let ok: bool = msg_send![&*pb, setString: &*ns, forType: NSPasteboardTypeString];
            if ok {
                Ok(())
            } else {
                Err("Failed to write text to pasteboard".to_string())
            }
        })
    }
}

#[cfg(not(target_os = "macos"))]
mod mac {
    pub struct PasteboardSnapshot {
        pub change_count: i64,
        pub text: Option<String>,
        pub image: Option<(String, Vec<u8>)>,
        pub source_app: Option<String>,
        pub concealed: bool,
    }
    pub fn change_count() -> i64 {
        i64::MIN
    }
    pub fn snapshot() -> Option<PasteboardSnapshot> {
        None
    }
    pub fn write_text(_text: &str) -> Result<(), String> {
        Err("Clipboard write not supported on this platform".to_string())
    }
}

/// Run `f` on the app's main thread and wait for its result.
///
/// `NSPasteboard` is an AppKit object and is only safe to touch on the main
/// thread; reading it from a background thread races with concurrent clipboard
/// changes and crashes via `__NSFastEnumerationMutationHandler`. We hop onto the
/// main thread for every pasteboard access and block the caller (a background
/// poller / command worker) until the value comes back over a channel.
#[cfg(target_os = "macos")]
fn run_on_main<T, F>(app: &AppHandle, f: F) -> Option<T>
where
    T: Send + 'static,
    F: FnOnce() -> T + Send + 'static,
{
    let (tx, rx) = std::sync::mpsc::channel();
    if app
        .run_on_main_thread(move || {
            let _ = tx.send(f());
        })
        .is_err()
    {
        return None;
    }
    rx.recv().ok()
}

fn poll_change_count(app: &AppHandle) -> i64 {
    #[cfg(target_os = "macos")]
    {
        run_on_main(app, mac::change_count).unwrap_or(i64::MIN)
    }
    #[cfg(not(target_os = "macos"))]
    {
        let _ = app;
        mac::change_count()
    }
}

fn poll_snapshot(app: &AppHandle) -> Option<mac::PasteboardSnapshot> {
    #[cfg(target_os = "macos")]
    {
        run_on_main(app, mac::snapshot).flatten()
    }
    #[cfg(not(target_os = "macos"))]
    {
        let _ = app;
        mac::snapshot()
    }
}

fn capture_snapshot(
    app: &AppHandle,
    db: &AgentDatabase,
    snap: mac::PasteboardSnapshot,
) -> Result<bool, String> {
    if snap.concealed {
        return Ok(false);
    }

    let now = now_secs();

    // Prefer image if present; otherwise text.
    if let Some((mime, bytes)) = snap.image {
        if bytes.is_empty() {
            return Ok(false);
        }
        let hash = hash_bytes(&bytes);
        if let Some(_) = db.clipboard_touch_if_recent_dup(&hash, now)? {
            emit_changed(app, db);
            return Ok(true);
        }
        let path = save_image_bytes(&bytes, &mime)?;
        let entry = NewClipboardEntry {
            kind: "image".to_string(),
            text: None,
            image_path: Some(path),
            source_app: snap.source_app,
            byte_len: bytes.len(),
            content_hash: hash,
            created_at: now,
        };
        db.clipboard_insert(&entry)?;
    } else if let Some(text) = snap.text {
        if text.trim().is_empty() {
            return Ok(false);
        }
        if text.len() > MAX_TEXT_BYTES {
            return Ok(false);
        }
        let hash = hash_text(&text);
        if let Some(_) = db.clipboard_touch_if_recent_dup(&hash, now)? {
            emit_changed(app, db);
            return Ok(true);
        }
        let entry = NewClipboardEntry {
            kind: "text".to_string(),
            text: Some(text.clone()),
            image_path: None,
            source_app: snap.source_app,
            byte_len: text.len(),
            content_hash: hash,
            created_at: now,
        };
        db.clipboard_insert(&entry)?;
    } else {
        return Ok(false);
    }

    let evicted = db.clipboard_evict(MAX_TEXT_ENTRIES, MAX_IMAGE_ENTRIES)?;
    for path in evicted {
        remove_image_file(&path);
    }
    emit_changed(app, db);
    Ok(true)
}

pub fn spawn_watcher(app: AppHandle, db: Arc<AgentDatabase>) {
    std::thread::spawn(move || {
        // Prime with the current changeCount so we don't capture whatever was on
        // the pasteboard at app start.
        let mut last_change = poll_change_count(&app);
        loop {
            std::thread::sleep(Duration::from_millis(POLL_INTERVAL_MS));
            // Cheap check first: only pay for a full pasteboard read (and the
            // main-thread hop it requires) when the clipboard actually changed.
            let change_count = poll_change_count(&app);
            if change_count == last_change {
                continue;
            }
            last_change = change_count;
            let snap = match poll_snapshot(&app) {
                Some(s) => s,
                None => continue,
            };
            last_change = snap.change_count;
            if let Err(err) = capture_snapshot(&app, &db, snap) {
                eprintln!("[clipboard-history] capture failed: {}", err);
            }
        }
    });
}

pub fn list(db: &AgentDatabase) -> Result<Vec<ClipboardEntry>, String> {
    db.clipboard_list(MAX_TEXT_ENTRIES + MAX_IMAGE_ENTRIES)
}

pub fn delete(db: &AgentDatabase, id: i64) -> Result<(), String> {
    if let Some(path) = db.clipboard_delete(id)? {
        remove_image_file(&path);
    }
    Ok(())
}

pub fn clear(db: &AgentDatabase) -> Result<(), String> {
    let paths = db.clipboard_clear()?;
    for p in paths {
        remove_image_file(&p);
    }
    Ok(())
}

/// Compose selected entries into a single string and write it to the system
/// pasteboard. When multiple entries are composed and `include_source` is true,
/// each entry is prefixed with a "Source:\ncontent" header. A single-entry
/// compose always emits raw content (no header).
pub fn compose(
    app: &AppHandle,
    db: &AgentDatabase,
    ids: &[i64],
    separator: &str,
    include_source: bool,
) -> Result<String, String> {
    let mut entries = Vec::new();
    for id in ids {
        if let Some(entry) = db.clipboard_get(*id)? {
            entries.push(entry);
        }
    }

    let multi = entries.len() > 1;
    let parts: Vec<String> = entries
        .into_iter()
        .filter_map(|entry| {
            let body = entry.text.clone().or_else(|| entry.image_path.clone())?;
            if multi && include_source {
                let source = entry
                    .source_app
                    .as_deref()
                    .filter(|s| !s.trim().is_empty())
                    .unwrap_or("Unknown");
                Some(format!("{}:\n{}", source, body))
            } else {
                Some(body)
            }
        })
        .collect();

    let composed = parts.join(separator);
    if !composed.is_empty() {
        #[cfg(target_os = "macos")]
        {
            // Writing the pasteboard mutates AppKit state and must happen on the
            // main thread, same as reads.
            let to_write = composed.clone();
            match run_on_main(app, move || mac::write_text(&to_write)) {
                Some(result) => result?,
                None => return Err("Failed to dispatch clipboard write to main thread".to_string()),
            }
        }
        #[cfg(not(target_os = "macos"))]
        {
            let _ = app;
            mac::write_text(&composed)?;
        }
    }
    Ok(composed)
}
